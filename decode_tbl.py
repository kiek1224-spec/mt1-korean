"""MT1 타일코드 -> 가나 디코더 (공용)"""
CH = {}
for i in range(10): CH[i] = "0123456789"[i]
for i, c in enumerate("アイウエオカキクケコサシスセソタチツテトナニヌネノハヒフヘホマミムメモヤユヨラリルレロワヲン"): CH[0x24+i] = c
for i, c in enumerate("ァィャュョッ"): CH[0x52+i] = c
CH[0x58]="゛"; CH[0x59]="゜"; CH[0x5A]="!"; CH[0x5B]="?"; CH[0x5C]="ー"; CH[0x5D]="・"
for i, c in enumerate("あいうえおかきくけこさしすせそたちつてとなにぬねのはひふへほまみむめもやゆよらりるれろわをん"): CH[0x64+i] = c
for i, c in enumerate("ぁぃゃゅょっ"): CH[0x92+i] = c
CH[0x98]="゛"; CH[0x99]="゜"
for i in range(26): CH[0x9A+i] = chr(ord('A')+i)
CH[0xB6]="ジ"; CH[0xB7]="ュ"; CH[0xB8]="ジ"; CH[0xB9]="ン"
CH[0xBA]="ゲ"; CH[0xBB]="ン"; CH[0xBC]="ェ"; CH[0xCC]="ォ"
_D = [("カ゛","ガ"),("キ゛","ギ"),("ク゛","グ"),("ケ゛","ゲ"),("コ゛","ゴ"),("サ゛","ザ"),("シ゛","ジ"),
      ("ス゛","ズ"),("セ゛","ゼ"),("ソ゛","ゾ"),("タ゛","ダ"),("チ゛","ヂ"),("ツ゛","ヅ"),("テ゛","デ"),
      ("ト゛","ド"),("ハ゛","バ"),("ヒ゛","ビ"),("フ゛","ブ"),("ヘ゛","ベ"),("ホ゛","ボ"),("ハ゜","パ"),
      ("ヒ゜","ピ"),("フ゜","プ"),("ヘ゜","ペ"),("ホ゜","ポ"),("ウ゛","ヴ"),
      ("か゛","が"),("き゛","ぎ"),("く゛","ぐ"),("け゛","げ"),("こ゛","ご"),("さ゛","ざ"),("し゛","じ"),
      ("す゛","ず"),("せ゛","ぜ"),("そ゛","ぞ"),("た゛","だ"),("ち゛","ぢ"),("つ゛","づ"),("て゛","で"),
      ("と゛","ど"),("は゛","ば"),("ひ゛","び"),("ふ゛","ぶ"),("へ゛","べ"),("ほ゛","ぼ"),("は゜","ぱ"),
      ("ひ゜","ぴ"),("ふ゜","ぷ"),("へ゜","ぺ"),("ほ゜","ぽ")]
def dec(s):
    o = "".join(CH.get(c, "<%02X>" % c) for c in s)
    for a, b in _D: o = o.replace(a, b)
    return o
